// The laws gate (npm run laws). Bend checks PROOF.bend, which fills every law of LAWS.bend, and with
// --verdict rechecks it with BendTT's kernel, which has a proof in Lean (Lean v4.34.0 must be
// installed). CLAIMS.bend must type-check with only its open claims missing. The ES modules that the
// oracle tests import (laws/generated/) must be what the models compile to now.
//
//   node laws/check.mjs           the gate, with --verdict
//   node laws/check.mjs --fast    the gate without --verdict (no Lean needed)
//   node laws/check.mjs --write   regenerate laws/generated/ from the models
import { execFile } from 'node:child_process'
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { homedir, tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs, promisify } from 'node:util'

const exec = promisify(execFile)
const here = dirname(fileURLToPath(import.meta.url))
const MODELS = ['patch', 'chunk', 'omit', 'history', 'entry']
const { values: args } = parseArgs({ options: { fast: { type: 'boolean', default: false }, write: { type: 'boolean', default: false } } })

const installed = join(homedir(), '.bend', 'bin', 'bend')
const bendBin = process.env.BEND ?? (existsSync(installed) ? installed : 'bend')

// bend prints its verdict and exits non-zero on SOME PROOFS FAIL; the output is what we judge.
const bend = async (bendArgs) => {
  try {
    const { stdout, stderr } = await exec(bendBin, bendArgs, { cwd: here, maxBuffer: 64 * 1024 * 1024 })
    return `${stdout}${stderr}`
  } catch (error) {
    if (error.code === 'ENOENT') throw new Error(`bend not found: install it (curl -fsSL https://bend-lang.com/install.sh | sh) or set BEND`)
    return `${error.stdout ?? ''}${error.stderr ?? ''}`
  }
}

// Each module's default export maps a def's name to a function; the tests give its values their shapes.
const DECLARATION = `// Generated by laws/check.mjs --write: the ES module bend compiles the model to.
declare const model: Record<string, (...args: unknown[]) => unknown>
export default model
`

const exportModels = async (dir) => {
  for (const model of MODELS) {
    const out = await bend([`${model}.bend`, '-o', join(dir, `${model}.mjs`)])
    if (!existsSync(join(dir, `${model}.mjs`))) throw new Error(`${model}.bend did not compile:\n${out}`)
    writeFileSync(join(dir, `${model}.d.mts`), DECLARATION)
  }
}

const failures = []

if (args.write) {
  await exportModels(join(here, 'generated'))
  console.log(`[laws] wrote laws/generated/ from ${MODELS.length} models`)
} else {
  const proofs = await bend(['PROOF.bend', ...(args.fast ? [] : ['--verdict'])])
  if (!/ALL PROOFS CHECK/.test(proofs)) failures.push(`PROOF.bend${args.fast ? '' : ' --verdict'}:\n${proofs.trim()}`)

  const claims = await bend(['CLAIMS.bend', '--check-only'])
  const claimCount = (readFileSync(join(here, 'CLAIMS.bend'), 'utf8').match(/^law /gm) ?? []).length
  if (!new RegExp(`Error: ${claimCount} TODOs found\\.`).test(claims) && !(claimCount === 0 && /ALL PROOFS CHECK/.test(claims))) {
    failures.push(`CLAIMS.bend must type-check with only its ${claimCount} open claims missing:\n${claims.trim()}`)
  }

  const fresh = mkdtempSync(join(tmpdir(), 'laws-'))
  try {
    await exportModels(fresh)
    for (const file of MODELS.flatMap((model) => [`${model}.mjs`, `${model}.d.mts`])) {
      const committed = join(here, 'generated', file)
      if (!existsSync(committed) || readFileSync(committed, 'utf8') !== readFileSync(join(fresh, file), 'utf8')) {
        failures.push(`laws/generated/${file} is not what the models compile to: run npm run laws:write`)
      }
    }
  } finally {
    rmSync(fresh, { recursive: true, force: true })
  }

  if (failures.length > 0) {
    console.error(`[laws] FAILED:\n\n${failures.map((failure) => `- ${failure}`).join('\n\n')}`)
    process.exitCode = 1
  } else {
    console.log(`[laws] ${args.fast ? 'proofs check' : 'proofs check with --verdict'}; ${claimCount} claims stated; generated modules current`)
  }
}
